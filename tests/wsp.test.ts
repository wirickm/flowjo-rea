// FlowJo workspace interoperability: counts computed by this app vs the
// population counts FlowJo itself recorded in FlowJo-saved .wsp files.
import { readdirSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { SampleEngine } from '../src/core/analysis';
import { parseFcs, type FcsFile } from '../src/core/fcs';
import { populationPath } from '../src/core/model';
import { parseWsp } from '../src/core/wsp';
import { fk, haveFixtures, readBytes, readText } from './fixtures';

const fcsCache = new Map<string, FcsFile>();
function loadFcs(dir: string, name: string): FcsFile {
  const key = `${dir}/${name}`;
  if (!fcsCache.has(key)) {
    const p = readdirSync(fk(dir)).includes('fcs_files') ? `${dir}/fcs_files/${name}` : `${dir}/${name}`;
    fcsCache.set(key, parseFcs(readBytes(p)));
  }
  return fcsCache.get(key)!;
}

export const WSP_CASES = [
  'simple_diamond_example/simple_diamond_example_quad_gate.wsp',
  'simple_diamond_example/test_data_diamond_asinh_rect.wsp',
  'simple_diamond_example/test_data_diamond_asinh_rect2.wsp',
  'simple_diamond_example/test_data_diamond_biex_rect.wsp',
  'simple_line_example/simple_poly_and_rect.wsp',
  'simple_line_example/simple_poly_and_rect_v2_poly50.wsp',
  'simple_line_example/single_ellipse_51_events.wsp',
  '8_color_data_set/8_color_ICS_simple.wsp',
  '8_color_data_set/8_color_ICS.wsp',
  '8_color_data_set/8_color_ICS_with_ellipse.wsp',
  '8_color_data_set/8_color_ICS_boolean_gate_testing.wsp',
  '8_color_data_set/8_color_ICS_dot_gate_name.wsp',
  '8_color_data_set/8_color_ICS_sample_without_gates.wsp',
  '8_color_data_set/reused_quad_gate_with_child.wsp',
];

export function compareWsp(path: string) {
  const dir = path.split('/')[0];
  const imp = parseWsp(readText(path));
  const rows: { sample: string; path: string; flowjo: number; ours: number }[] = [];
  for (const s of imp.workspace.samples) {
    const fcs = loadFcs(dir, s.fileName);
    const eng = new SampleEngine(fcs, s, imp.workspace.matrices).run();
    const fj = imp.flowjoCounts[s.fileName];
    for (const p of s.populations) {
      const key = populationPath(s.populations, p.id);
      const r = eng.results.get(p.id)!;
      if (r.error) throw new Error(`${key}: ${r.error}`);
      // FlowJo writes count="0"/"-1" for nodes it never computed; skip those.
      if (fj[key] === undefined || fj[key] <= 0) continue;
      rows.push({ sample: s.fileName, path: key, flowjo: fj[key], ours: r.count });
    }
  }
  return { imp, rows };
}

// Workspaces where every FlowJo-computed count is reproduced exactly.
const EXACT = new Set([
  'simple_diamond_example/simple_diamond_example_quad_gate.wsp',
  'simple_diamond_example/test_data_diamond_asinh_rect.wsp',
  'simple_diamond_example/test_data_diamond_asinh_rect2.wsp',
  'simple_diamond_example/test_data_diamond_biex_rect.wsp',
  'simple_line_example/single_ellipse_51_events.wsp',
  '8_color_data_set/reused_quad_gate_with_child.wsp',
]);

describe.skipIf(!haveFixtures)('FlowJo .wsp import reproduces FlowJo-recorded counts', () => {
  const report: string[] = ['| Workspace | Sample | Population | FlowJo | flowjo-rea | Diff |', '| --- | --- | --- | ---: | ---: | ---: |'];
  for (const c of WSP_CASES) {
    it(c, () => {
      const { rows } = compareWsp(c);
      for (const r of rows) report.push(`| ${c.split('/')[1]} | ${r.sample.slice(0, 22)} | ${r.path} | ${r.flowjo} | ${r.ours} | ${r.ours - r.flowjo} |`);
      if (EXACT.has(c)) {
        for (const r of rows) expect(r.ours, `${r.sample} ${r.path}`).toBe(r.flowjo);
      } else {
        // Known gap (docs/compatibility-matrix.md): workspaces with polygon
        // gates differ from FlowJo (Singlets ~0.25%; worst 10 events on a
        // 74-event population). Cause unidentified. Regression bound measured
        // on the current implementation: |diff| <= 1% of FlowJo count + 10.
        // The ellipse on logicle axes in 8_color_ICS_with_ellipse differs by
        // 2-3.2%; bounded separately at 4%.
        for (const r of rows) {
          const rel = r.path.endsWith('ellipse1') ? 0.04 : 0.01;
          expect(Math.abs(r.ours - r.flowjo), `${r.sample} ${r.path}`).toBeLessThanOrEqual(rel * r.flowjo + 10);
        }
      }
    });
  }
  it.runIf(process.env.WRITE_REPORT === '1')('write report', async () => {
    const { writeFileSync, mkdirSync } = await import('node:fs');
    mkdirSync('docs/validation', { recursive: true });
    writeFileSync('docs/validation/wsp-counts.md', `# FlowJo count comparison\n\nGenerated by \`WRITE_REPORT=1 npx vitest run tests/wsp.test.ts\`. FlowJo column = count attribute FlowJo saved in the .wsp; nodes FlowJo saved as 0/-1 (not computed) are omitted.\n\n${report.join('\n')}\n`);
  });
});
