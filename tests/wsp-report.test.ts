// Writes docs/validation/wsp-counts.md. Run: WRITE_REPORT=1 npx vitest run tests/wsp-report.test.ts
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { fk, haveFixtures } from './fixtures';
import { compareWsp, decompose, fcsPath, WSP_CASES, type CompareRow } from './wspCompare';

const sha = (p: string) => createHash('sha256').update(readFileSync(fk(p))).digest('hex');
const pct = (v: number) => `${(100 * v).toFixed(2)}%`;
const sgn = (v: number) => (v > 0 ? `+${v}` : String(v));

describe.runIf(haveFixtures && process.env.WRITE_REPORT === '1')('write FlowJo count report', () => {
  it('writes docs/validation/wsp-counts.md', () => {
    const commit = execFileSync('git', ['-C', fk('..'), 'rev-parse', 'HEAD']).toString().trim();
    const prov: string[] = [];
    const table: string[] = [];
    const all: (CompareRow & { ws: string })[] = [];
    const fcsSeen = new Map<string, string>();
    for (const c of WSP_CASES) {
      const { imp, rows } = compareWsp(c);
      prov.push(`| ${c} | ${imp.flowjoVersion} | ${sha(c).slice(0, 16)} | ${rows.length} |`);
      for (const s of imp.workspace.samples) fcsSeen.set(fcsPath(c.split('/')[0], s.fileName), '');
      for (const r of rows) all.push({ ...r, ws: c.split('/')[1].replace('.wsp', '') });
    }
    for (const r of all) {
      const d = decompose(r);
      const diff = r.ours - r.flowjo;
      table.push(
        `| ${r.ws} | ${r.sample.replace(/^101_DEN084Y5_15_|_clean\.fcs$/g, '')} | ${r.path} | ${r.gateType} | ${r.fjParent ?? 'n/a'} | ${r.ourParent} | ${r.flowjo} | ${r.ours} | ${sgn(diff)} | ${pct(diff / r.flowjo)} | ${d ? pct(d.fFJ) : 'n/a'} | ${d ? pct(d.fOurs) : 'n/a'} | ${d ? d.inherited.toFixed(1) : 'n/a'} | ${d ? d.introduced.toFixed(1) : 'n/a'} |`,
      );
    }
    // Summary by gate type using the introduced component.
    const byType = new Map<string, (CompareRow & { ws: string })[]>();
    for (const r of all) byType.set(r.gateType, [...(byType.get(r.gateType) ?? []), r]);
    const summary = [...byType.entries()].map(([t, rs]) => {
      const exact = rs.filter((r) => r.ours === r.flowjo).length;
      const intro = rs.map((r) => decompose(r)).filter((d): d is NonNullable<typeof d> => !!d);
      const worstIntro = Math.max(0, ...intro.map((d) => Math.abs(d.introduced)));
      const worstFreq = Math.max(0, ...intro.map((d) => Math.abs(d.fOurs - d.fFJ)));
      return `| ${t} | ${rs.length} | ${exact} | ${worstIntro.toFixed(1)} | ${(100 * worstFreq).toFixed(3)} pp |`;
    });
    const exactN = all.filter((r) => r.ours === r.flowjo).length;
    const md = `# FlowJo count comparison

Generated by \`WRITE_REPORT=1 npx vitest run tests/wsp-report.test.ts\` after
\`./scripts/fetch-fixtures.sh\`. Do not edit by hand.

## Reference source

- Fixtures: FlowKit (BSD-3-Clause) commit \`${commit}\`, https://github.com/whitews/FlowKit, \`data/\`.
- Reference values: the \`count\` attribute FlowJo wrote on each population
  when it saved the workspace. Nodes FlowJo saved as 0 or -1 (not computed)
  are omitted, which is why some workspaces contribute no rows.
- These are the only FlowJo outputs available; no FlowJo installation was used.

| Workspace | Saved by FlowJo | SHA-256 (prefix) | Compared populations |
| --- | --- | --- | ---: |
${prov.join('\n')}

| FCS file | SHA-256 (prefix) |
| --- | --- |
${[...fcsSeen.keys()].map((p) => `| ${p} | ${sha(p).slice(0, 16)} |`).join('\n')}

## How to read the columns

- **Diff** = ours - FlowJo; **Diff %** = Diff / FlowJo count of *that
  population* (population-relative).
- **f** = count / parent count (frequency of parent), for FlowJo and ours.
- **Inherited** = f_FlowJo x (our parent - FlowJo parent): events explained by
  the parent's difference if this gate selected the same fraction.
- **Introduced** = our parent x (f_ours - f_FlowJo): the part attributable to
  this gate. Inherited + Introduced = Diff exactly. This is a population-level
  attribution; without FlowJo event-level output it cannot say which events differ.
- Top-level parents are the sample's total event count.

## Summary by gate type and axis scales (${all.length} populations, ${exactN} exact)

"Exact" applies to these fixtures only; it is not evidence that a gate type
is compatible in general.

| Gate type [x,y scales] | Populations | Exact | Worst \\|introduced\\| (events) | Worst \\|f diff\\| |
| --- | ---: | ---: | ---: | ---: |
${summary.join('\n')}

## Every population

| Workspace | Sample | Population | Gate | FlowJo parent | Our parent | FlowJo | Ours | Diff | Diff % | f FlowJo | f ours | Inherited | Introduced |
| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${table.join('\n')}
`;
    writeFileSync('docs/validation/wsp-counts.md', md);
  });
});
