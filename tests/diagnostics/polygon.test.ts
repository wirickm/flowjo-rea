// Diagnostic (not a compatibility test): for top-level-parent-matched polygon
// gates, how wide a boundary band would explain FlowJo's count?
// Run: DIAG=1 npx vitest run tests/diagnostics/polygon.test.ts
import { writeFileSync } from 'node:fs';
import { describe, it } from 'vitest';
import { SampleEngine } from '../../src/core/analysis';
import { parseFcs } from '../../src/core/fcs';
import { populationPath } from '../../src/core/model';
import { parseWsp } from '../../src/core/wsp';
import { haveFixtures, readBytes, readText } from '../fixtures';

function segDist(px: number, py: number, ax: number, ay: number, bx: number, by: number) {
  const dx = bx - ax, dy = by - ay;
  const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy || 1)));
  return Math.hypot(px - ax - t * dx, py - ay - t * dy);
}

describe.runIf(haveFixtures && process.env.DIAG === '1')('polygon boundary diagnostic', () => {
  it('writes docs/validation/polygon-diagnostics.md', () => {
    const imp = parseWsp(readText('8_color_data_set/8_color_ICS.wsp'));
    const lines: string[] = [];
    for (const s of imp.workspace.samples) {
      const fcs = parseFcs(readBytes(`8_color_data_set/fcs_files/${s.fileName}`));
      const eng = new SampleEngine(fcs, s, imp.workspace.matrices).run();
      for (const p of s.populations) {
        if (p.gate.type !== 'polygon' || !p.parentId) continue;
        const path = populationPath(s.populations, p.id);
        const fj = imp.flowjoCounts[s.fileName][path];
        const fjParent = imp.flowjoCounts[s.fileName][populationPath(s.populations, p.parentId)];
        const parentMask = eng.masks.get(p.parentId)!;
        const r = eng.results.get(p.id)!;
        // Only polygons whose parent count equals FlowJo's: no inherited part.
        const inheritedFree = r.parentCount === fjParent;
        const g = p.gate;
        const xs = eng.dimension(g.dims[0]);
        const ys = eng.dimension(g.dims[1]);
        // Normalise each axis to the FlowJo 256-unit display so distances are in display bins.
        const span = g.dims.map((d, k) => {
          const v = g.vertices.map((q) => q[k]);
          return d.transform.kind === 'none' ? 262144 / 256 : 1 / 256;
        });
        const V = g.vertices.map(([a, b]) => [a / span[0], b / span[1]]);
        const mask = eng.masks.get(p.id)!;
        const outside: number[] = [];
        const inside: number[] = [];
        for (let i = 0; i < mask.length; i++) {
          if (!parentMask[i]) continue;
          const x = xs[i] / span[0], y = ys[i] / span[1];
          let d = Infinity;
          for (let a = 0, b = V.length - 1; a < V.length; b = a++) d = Math.min(d, segDist(x, y, V[a][0], V[a][1], V[b][0], V[b][1]));
          (mask[i] ? inside : outside).push(d);
        }
        outside.sort((a, b) => a - b);
        inside.sort((a, b) => a - b);
        const need = fj - r.count;
        const band = need > 0 ? outside[need - 1] : need < 0 ? -inside[-need - 1] : 0;
        const within = (arr: number[], w: number) => arr.filter((d) => d <= w).length;
        lines.push(`| ${s.fileName.slice(16, 23)} | ${path} | ${g.dims.map((d) => d.transform.kind === 'none' ? 'linear' : d.transform.kind).join(',')} | ${inheritedFree ? 'yes' : 'no'} | ${fj} | ${r.count} | ${need} | ${band.toFixed(3)} | ${within(outside, 0.5)} | ${within(outside, 1)} | ${within(inside, 0.5)} |`);
      }
    }
    writeFileSync('docs/validation/polygon-diagnostics.md', `# Polygon boundary diagnostic

Generated by \`DIAG=1 npx vitest run tests/diagnostics/polygon.test.ts\` on
8_color_ICS.wsp (FlowJo 10.6.2). Distances are in FlowJo display bins (axis
range / 256; logicle axes use the logicle 0..1 scale / 256).

**Band needed** = the distance d such that adding all parent events outside
the polygon within d (or removing those inside within d when negative) would
reproduce FlowJo's count. A constant band across samples and gates would
support a boundary-rasterisation explanation; a varying band argues against it.

| Sample | Population | Axes | Parent equal to FlowJo | FlowJo | Ours | Needed | Band needed (bins) | Outside within 0.5 bin | Outside within 1 bin | Inside within 0.5 bin |
| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |
${lines.join('\n')}
`);
  });
});
